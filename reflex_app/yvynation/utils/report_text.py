"""Explanatory text for the laid-out territory report (docs/PDF_REPORT.md §2.8, §3a).

Deterministic templates in en (reference and fallback), pt, es and fr. Every
sentence is filled from the same records the section's chart and table are
drawn from — nothing is recomputed here beyond sums and shares of those rows.

**Describe, never judge.** Sentences state quantities, changes over the period
and differences between the territory and its buffer. They never attribute a
change to a cause, to protection or to governance, and carry no legal or
compliance vocabulary. The causal reading belongs to the offline governance
reports in ``utils/``, not to a per-area export.

Numbers are formatted by ``report_kit.text`` so a Portuguese report reads
"1.234,5 ha" and an English one "1,234.5 ha".
"""

