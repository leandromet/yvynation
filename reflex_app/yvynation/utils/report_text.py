def fmt_signed(value, decimals: int = 1, lang: str = "en") -> str:
    """The kit's signed number with an ASCII hyphen for the minus: the kit's
    Noto Sans subset has no U+2212, so its true minus prints as a blank in
    the PDF (reported upstream; drop this wrapper once the kit is fixed)."""
    return _kit_signed(value, decimals, lang).replace("\u2212", "-")


