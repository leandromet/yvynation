def missing_keys() -> Dict[str, List[str]]:
    """Template keys present in English but absent from another language."""
    en = set(TEXT["en"])
    return {lang: sorted(en - set(TEXT[lang])) for lang in LANGS if lang != "en"}


def s(key: str, lang: str, **kw) -> str:
    """A template in ``lang`` (fallback en), filled with ``kw``."""
    table = TEXT.get(lang) or TEXT["en"]
    text = table.get(key) or TEXT["en"][key]
    return text.format(**kw) if kw else text


def km_label(km: Optional[float], lang: str) -> str:
    return fmt_num(km, 0 if km is None or float(km).is_integer() else 1, lang)


# --------------------------------------------------------------------------- #
# Reading sentences — (numbers, lang) → str. Numbers come from the section's
# own table rows; only sums and shares of those rows are taken here.
# --------------------------------------------------------------------------- #

def _direction(delta: float, lang: str) -> str:
    if abs(delta) < 0.05:
        return s("dir_same", lang)
    key = "dir_up" if delta > 0 else "dir_down"
    return s(key, lang, d=fmt_ha(abs(delta), 0, lang))


def landcover_reading(rows: Sequence[Tuple[str, float, float]], y1, y2,
                      lang: str) -> str:
    """``rows``: (class name, area y1 ha, area y2 ha). One sentence on the
    largest class of y1, one on the class with the largest change among the
    others."""
    rows = [r for r in rows if (r[1] or 0) > 0 or (r[2] or 0) > 0]
    if not rows:
        return ""
    tot1 = sum(r[1] or 0 for r in rows) or 1.0
    tot2 = sum(r[2] or 0 for r in rows) or 1.0
    top = max(rows, key=lambda r: r[1] or 0)
    a1, a2 = top[1] or 0.0, top[2] or 0.0
    text = s("lc_reading", lang, y1=y1, y2=y2, cls=top[0],
             a1=fmt_ha(a1, 0, lang), p1=fmt_pct(a1 / tot1 * 100, 1, lang),
             a2=fmt_ha(a2, 0, lang), p2=fmt_pct(a2 / tot2 * 100, 1, lang),
             direction=_direction(a2 - a1, lang))
    others = [r for r in rows if r is not top]
    if others:
        mover = max(others, key=lambda r: abs((r[2] or 0) - (r[1] or 0)))
        d = (mover[2] or 0) - (mover[1] or 0)
        if abs(d) >= 0.5:
            key = "lc_second_up" if d > 0 else "lc_second_down"
            text += " " + s(key, lang, cls=mover[0], d=fmt_ha(abs(d), 0, lang))
    return text


def gains_losses_reading(rows: Sequence[Tuple[str, float, float]], lang: str) -> str:
    deltas = [(r[0], (r[2] or 0) - (r[1] or 0)) for r in rows]
    gains = [d for d in deltas if d[1] > 0]
    losses = [d for d in deltas if d[1] < 0]
    if not gains and not losses:
        return ""
    g = sum(d[1] for d in gains)
    lo = sum(d[1] for d in losses)
    cg = max(gains, key=lambda d: d[1]) if gains else ("—", 0.0)
    cl = min(losses, key=lambda d: d[1]) if losses else ("—", 0.0)
    return s("gl_reading", lang, g=fmt_ha(g, 0, lang), l=fmt_ha(abs(lo), 0, lang),
             cg=cg[0], dg=fmt_signed(cg[1], 0, lang) + " ha",
             cl=cl[0], dl=fmt_signed(cl[1], 0, lang) + " ha")


def transitions_reading(top: Sequence[Tuple[str, str, float]], total: float,
                        lang: str) -> str:
    if not top or total <= 0:
        return s("tr_none", lang)
    a, b, ha = top[0]
    return s("tr_reading", lang, total=fmt_ha(total, 0, lang), a=a, b=b,
             ha=fmt_ha(ha, 0, lang), pct=fmt_pct(ha / total * 100, 1, lang))


def gfc_reading(loss_ha: float, cover_ha: float, by_year: Sequence[Tuple[int, float]],
                lang: str) -> str:
    if not by_year or loss_ha <= 0:
        return s("gfc_reading_none", lang)
    year, ha = max(by_year, key=lambda r: r[1])
    last = max(y for y, _ in by_year)
    pct = loss_ha / cover_ha * 100 if cover_ha > 0 else None
    return s("gfc_reading", lang, loss=fmt_ha(loss_ha, 0, lang), last=last,
             pct=fmt_pct(pct, 1, lang), year=year, ha=fmt_ha(ha, 0, lang))


def glad_reading(year, cls: str, ha: float, total: float, lang: str) -> str:
    return s("glad_reading", lang, year=year, cls=cls, ha=fmt_ha(ha, 0, lang),
             pct=fmt_pct(ha / total * 100 if total else None, 1, lang))


def buffer_reading(t_pp: Optional[float], b_pp: Optional[float], km, lang: str) -> str:
    if t_pp is None or b_pp is None:
        return ""
    return s("buf_reading", lang, t=fmt_signed(t_pp, 1, lang), b=fmt_signed(b_pp, 1, lang),
             km=km_label(km, lang), gap=fmt_signed(b_pp - t_pp, 1, lang))


def buffer_gfc_reading(t_pct: Optional[float], b_pct: Optional[float], lang: str) -> str:
    if t_pct is None or b_pct is None:
        return ""
    return s("buf_reading_gfc", lang, t=fmt_pct(t_pct, 1, lang), b=fmt_pct(b_pct, 1, lang))
